export type MessageKey = keyof typeof zh;

const tables: Record<Locale, Record<MessageKey, string>> = { "zh-CN": zh, en };

export const languageSetting = ref<Language>("system");

export function systemLocale(): Locale {
  const lang = navigator.language.toLowerCase();
  return lang.startsWith("zh") ? "zh-CN" : "en";
}

export const locale = computed<Locale>(() =>
  languageSetting.value === "system" ? systemLocale() : languageSetting.value,
);

function fill(text: string, vars?: Record<string, string | number>) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function t(key: MessageKey, vars?: Record<string, string | number>) {
  return fill(tables[locale.value][key] ?? zh[key], vars);
}

