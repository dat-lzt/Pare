const patterns: Array<{ re: RegExp; key: MessageKey; name: "ext" | "name" | "code" }> = [
  { re: /^不支持 \.(.+)$/, key: "errUnsupportedExt", name: "ext" },
  { re: /^缺少引擎 (.+)$/, key: "errMissingEngine", name: "name" },
  { re: /^(.+) 未找到$/, key: "errEngineNotFound", name: "name" },
  { re: /^未知引擎 (.+)$/, key: "errUnknownEngine", name: "name" },
  { re: /^退出码 (-?\d+)$/, key: "errExit", name: "code" },
  { re: /^还没选择输出文件夹，结果会写到旁边的「(.+)」。$/, key: "errHintSibling", name: "name" },
  { re: /^还没选择输出文件夹，结果会写到「(.+)」。$/, key: "errHintFallback", name: "name" },
];

export function translateMessage(text: string) {
  if (!text) return "";
  const key = exact[text];
  if (key) return t(key);
  for (const pattern of patterns) {
    const match = text.match(pattern.re);
    if (match?.[1]) return t(pattern.key, { [pattern.name]: match[1] });
  }
  return text;
}

